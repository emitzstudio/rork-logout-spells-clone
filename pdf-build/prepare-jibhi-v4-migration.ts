/**
 * Writes backend/migrations/0112_jibhi_new_itinerary.sql from jibhi-v4-content.ts; never
 * connects to production. The migration replaces the live Jibhi spell's itinerary and the
 * page copy that described the four-day edition, moves the duration to 2 nights / 3 days and
 * attaches brochure v4. Dates, departure, prices, name, hook, gallery and the not-included
 * list are untouched, and every other spell and protected table is asserted unchanged.
 * Run: bun run prepare-jibhi-v4-migration.ts  (refuses to replace a different 0112 file)
 */
import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { JIBHI_ID, JIBHI_ORIGIN, JIBHI_V3_FILE, JIBHI_V4, JIBHI_V4_PAGE_KEYS, jibhiV4Content, plainStep } from "./jibhi-v4-content";

/* The live row as reviewed on 2026-09-29 (select md5(page::text), md5(inclusions::text), updated_at). */
const REVIEWED_UPDATED_AT = "2026-09-29T16:36:27.675417+00:00";
const REVIEWED_PAGE_MD5 = "95168ad26cdbec3ac2e221c51d0c1e54";
const REVIEWED_INCLUSIONS_MD5 = "47b834d8f940fd532dabbc9895412cab";
const CHANGE_ID = "b7e83d15-2c4a-4f09-9d61-84f2a6c9e3d9";

const content = JSON.stringify(jibhiV4Content, null, 2);
assert(!content.includes("$jibhi$"));
assert(!/[\u2013\u2014\u2192\u2022]/.test(content), "Page copy must stay free of em/en dashes, arrows and bullet glyphs");
assert.equal(jibhiV4Content.page.itinerary.length, 3);
assert.equal(jibhiV4Content.duration_days, 3);
assert.equal(jibhiV4Content.nights, 2);
assert.equal(jibhiV4Content.inclusions.length, 8);
assert.equal(jibhiV4Content.inclusions[0], "Accommodation in Jibhi (2 nights)");
assert.deepEqual(jibhiV4Content.page.included.map((item) => item.text), jibhiV4Content.inclusions);
assert.deepEqual(JIBHI_V4_PAGE_KEYS, ["about", "audience", "faqs", "host", "included", "itinerary", "quickInfo", "stay", "tripHighlights"]);
for (const [index, day] of JIBHI_V4.days.entries()) {
  const body = jibhiV4Content.page.itinerary[index]!.body;
  let cursor = 0;
  for (const step of day.steps) {
    const found = body.indexOf(`- ${step}`, cursor);
    assert(found >= cursor, `Day ${index + 1}: website body must carry every supplied line in order: ${plainStep(step)}`);
    cursor = found + step.length;
  }
}
assert(jibhiV4Content.page.itinerary[2]!.body.includes(JIBHI_V4.ending.line) && jibhiV4Content.page.itinerary[2]!.body.includes(JIBHI_V4.ending.note));
assert(!/four days|3 nights|three nights|Day 4|TODAY'S MOOD|Little Hideaways|Choose one beautiful trek/i.test(content), "Copy from the four-day edition remains");

const protectedSnapshot = `jsonb_build_object(
    'bookings', (select md5(coalesce(jsonb_agg(to_jsonb(x) order by x.id)::text, '[]')) from public.bookings x),
    'payments', (select md5(coalesce(jsonb_agg(to_jsonb(x) order by x.id)::text, '[]')) from public.payments x),
    'receipts', (select md5(coalesce(jsonb_agg(to_jsonb(x) order by x.id)::text, '[]')) from public.receipts x),
    'departures', (select md5(coalesce(jsonb_agg(to_jsonb(x) order by x.id)::text, '[]')) from public.spell_departures x),
    'forms', (select md5(coalesce(jsonb_agg(to_jsonb(x) order by x.id)::text, '[]')) from public.forms x),
    'changes', (select md5(coalesce(jsonb_agg(to_jsonb(x) order by x.id)::text, '[]')) from public.spell_changes x where x.id <> v_change_id),
    'others', (select md5(coalesce(jsonb_agg(to_jsonb(s) - array['views', 'updated_at'] order by s.id)::text, '[]')) from public.spells s where s.id <> v_id)
  )`;

const sql = `-- 0112: The Jibhi Spell moves to the founder's step-by-step itinerary (2026-09-29):
-- "SPELL TO JIBHI - 2 Nights / 3 Days, Delhi to Jibhi to Delhi". Day 1 Shoja, Jalori Pass and
-- Serolsar Lake; Day 2 Tirthan Valley, Chhoie Waterfall and Bahu Village; Day 3 Mini Thailand,
-- Jibhi Waterfall and the overnight journey home, reaching Delhi the next morning.
-- The website itinerary carries every supplied line in its order; the about story, host bio,
-- FAQs, stay block, quick info, audience, trip highlights and inclusions stop describing the
-- four-day edition; duration_days 4 -> 3 and nights 3 -> 2; pricing.brochureUrl moves to the
-- immutable v4 PDF (v1-v3 stay published). Deploy the v4 PDF before applying.
-- Untouched: name, hook, dates, the 1-4 October 2026 departure, prices, gallery, not-included
-- list, every other spell, bookings, payments, receipts, forms. The spell has no bookings.
-- Generated by pdf-build/prepare-jibhi-v4-migration.ts from pdf-build/jibhi-v4-content.ts.
do $$
declare
  v_id constant uuid := '${JIBHI_ID}';
  v_change_id constant uuid := '${CHANGE_ID}';
  v_old constant text := '${JIBHI_ORIGIN}/brochures/${JIBHI_V3_FILE}';
  v_content constant jsonb := $jibhi$${content}$jibhi$::jsonb;
  v_new constant text := v_content->>'brochureUrl';
  v_keys constant text[] := array[${JIBHI_V4_PAGE_KEYS.map((key) => `'${key}'`).join(", ")}];
  v_before public.spells%rowtype;
  v_after public.spells%rowtype;
  v_page jsonb;
  v_protected jsonb;
  v_protected_after jsonb;
  v_text text;
begin
  if jsonb_array_length(v_content->'page'->'itinerary') <> 3 or (v_content->>'duration_days')::int <> 3 or (v_content->>'nights')::int <> 2
    or jsonb_array_length(v_content->'inclusions') <> 8
    or (select array_agg(k order by k) from jsonb_object_keys(v_content->'page') k) <> v_keys then
    raise exception '0112: content projection mismatch';
  end if;

  select * into strict v_before from public.spells where id = v_id for update;
  if v_before.slug <> 'the-jibhi-spell' or v_before.status <> 'published' or v_before.deleted_at is not null
    or v_before.host_name <> 'Kavya Lilhare' then
    raise exception '0112: expected the published Kavya Jibhi spell';
  end if;

  if v_before.page #>> '{pricing,brochureUrl}' = v_new and v_before.duration_days = 3 and v_before.nights = 2
    and v_before.page->'itinerary' = v_content->'page'->'itinerary' then
    raise notice '0112 already applied - nothing to do';
    return;
  end if;
  if v_before.page #>> '{pricing,brochureUrl}' = v_new or v_before.duration_days <> 4 or v_before.nights <> 3
    or v_before.page->'itinerary' = v_content->'page'->'itinerary' then
    raise exception '0112: partially applied state; inspect before continuing';
  end if;
  if v_before.page #>> '{pricing,brochureUrl}' is distinct from v_old
    or v_before.updated_at <> '${REVIEWED_UPDATED_AT}'::timestamptz
    or md5(v_before.page::text) <> '${REVIEWED_PAGE_MD5}'
    or md5(v_before.inclusions::text) <> '${REVIEWED_INCLUSIONS_MD5}' then
    raise exception '0112: Jibhi changed since review; inspect before applying';
  end if;
  if exists (select 1 from public.bookings where spell_id = v_id) then
    raise exception '0112: Jibhi has bookings; needs a manual plan';
  end if;
  if not exists (select 1 from public.spell_departures d where d.spell_id = v_id and d.start_date = date '2026-10-01' and d.end_date = date '2026-10-04' and d.date_label = '1-4 October 2026') then
    raise exception '0112: the 1-4 October 2026 departure is not as reviewed';
  end if;

  select ${protectedSnapshot} into v_protected;

  v_page := jsonb_set(v_before.page || (v_content->'page'), '{pricing,brochureUrl}', v_content->'brochureUrl', false);
  update public.spells
     set page = v_page,
         inclusions = (select array_agg(t.value order by t.ordinality) from jsonb_array_elements_text(v_content->'inclusions') with ordinality t),
         duration_days = (v_content->>'duration_days')::int,
         nights = (v_content->>'nights')::int
   where id = v_id;

  select * into strict v_after from public.spells where id = v_id;
  if v_after.page is distinct from v_page
    or (v_after.page - v_keys - 'pricing') is distinct from (v_before.page - v_keys - 'pricing')
    or ((v_after.page->'pricing') - 'brochureUrl') is distinct from ((v_before.page->'pricing') - 'brochureUrl')
    or v_after.page #>> '{pricing,brochureUrl}' <> v_new
    or ((v_after.page->'host') - 'about') is distinct from ((v_before.page->'host') - 'about')
    or jsonb_array_length(v_after.page->'itinerary') <> 3
    or jsonb_array_length(v_after.page->'faqs') <> jsonb_array_length(v_before.page->'faqs')
    or jsonb_array_length(v_after.page->'included') <> 8
    or v_after.page->'notIncluded' is distinct from v_before.page->'notIncluded'
    or v_after.page->'gallery' is distinct from v_before.page->'gallery'
    or v_after.duration_days <> 3 or v_after.nights <> 2
    or v_after.inclusions <> (select array_agg(t.value order by t.ordinality) from jsonb_array_elements_text(v_content->'inclusions') with ordinality t)
    or v_after.updated_at <= v_before.updated_at
    or (to_jsonb(v_after) - array['page', 'inclusions', 'duration_days', 'nights', 'updated_at'])
       is distinct from (to_jsonb(v_before) - array['page', 'inclusions', 'duration_days', 'nights', 'updated_at']) then
    raise exception '0112: preservation check failed';
  end if;

  v_text := v_after.page::text;
  if position(chr(8211) in v_text) > 0 or position(chr(8212) in v_text) > 0 or position(chr(8594) in v_text) > 0 then
    raise exception '0112: em/en dash or arrow in page copy';
  end if;
  if lower(v_text) like '%four days%' or v_text like '%3 nights%' or lower(v_text) like '%three nights%'
    or v_text like '%Day 4%' or v_text like '%TODAY''S MOOD%' or v_text like '%Little Hideaways%' or v_text like '%Choose one beautiful trek%' then
    raise exception '0112: copy from the four-day edition remains';
  end if;
  if not (v_text like '%Serolsar Lake%' and v_text like '%Raghupur Fort%' and v_text like '%Jalori Pass (10,800 ft)%'
    and v_text like '%Chhoie Waterfall%' and v_text like '%Bahu Village%' and v_text like '%Mini Thailand%'
    and v_text like '%Jibhi Waterfall%' and v_text like '%Reach Delhi the next morning.%' and v_text like '%2 nights%') then
    raise exception '0112: supplied itinerary copy missing';
  end if;

  insert into public.spell_changes (id, spell_id, kind, title, detail) values
    (v_change_id, v_id, 'edited', 'New itinerary: Jalori Pass, Serolsar Lake, Tirthan Valley and Bahu Village',
     '2 nights / 3 days, Delhi to Jibhi to Delhi. Day 1 Shoja, Jalori Pass (10,800 ft), Raghupur Fort and Serolsar Lake; Day 2 Tirthan Valley, Chhoie Waterfall and Bahu Village; Day 3 Mini Thailand, Jibhi Waterfall, sunset by the Tirthan River and the overnight journey home. Brochure v4 attached. Dates (1-4 October 2026) and prices are unchanged.')
    on conflict (id) do nothing;

  select ${protectedSnapshot} into v_protected_after;
  if v_protected_after is distinct from v_protected then
    raise exception '0112: another spell or a protected table changed';
  end if;
  if (select count(*) from public.spells where status = 'published' and deleted_at is null and slug = 'the-jibhi-spell') <> 1 then
    raise exception '0112: visibility mismatch';
  end if;
end;
$$;
`;

const target = "../backend/migrations/0112_jibhi_new_itinerary.sql";
if (existsSync(target)) assert.equal(readFileSync(target, "utf8"), sql, "Refusing to replace a different migration");
else writeFileSync(target, sql, { flag: "wx" });
console.log(`Prepared ${target}; ${sql.length} characters; no production writes performed.`);
